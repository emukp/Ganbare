#!/usr/bin/env python3
"""
bdf2asm.py — fusion-pixel-12px BDF -> 12x12 1bpp glyph DEFB asm (sjasmplus)

输入:
  fonts/fusion-pixel-12px-monospaced-zh_hans.bdf  (12x12, ascent=10)
  textscn.tsv                                     (zh 列收集唯一汉字, 首现顺序编号)
输出:
  gfx/zh_glyphs_bank11.asm, ...  (每 bank 8KB, 字形 24B/个, 256 个/bank)
  tools/zh_glyph_index.tsv             (index / codepoint / char, 供 build_texts.py)

字形格式 (每字 24B): 12 行 x 2B, 行内 bit15..bit4 = 像素 0..11 (左对齐, MSB=最左像素)
ASM 注释仅用英文 (AGENTS.md 规则), 汉字以 U+XXXX 表示。

用法: python3 tools/bdf2asm.py [--test]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BDF = ROOT / "fonts" / "fusion-pixel-12px-monospaced-zh_hans.bdf"
TSV = ROOT / "textscn.tsv"
IDX_OUT = ROOT / "tools" / "zh_glyph_index.tsv"

GLYPH_BYTES = 24          # 12 rows * 2B
BANK_SIZE = 0x2000
PER_BANK = 256                # 与 bank10 ZhBankTable 的 8bit 计数一致 (须同步)
FIRST_BANK = 0x11

CELL = 12                 # 12x12 cell
ASCENT = 10               # FONT_ASCENT


def parse_bdf(path, wanted):
    """wanted: set of codepoints -> {codepoint: [12 行 16bit 左对齐位图]}"""
    glyphs = {}
    cur = {}
    state = None          # None | 'inchar' | 'bitmap'
    enc = None
    bbx = None
    rows = []
    with path.open(encoding="ascii") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("STARTCHAR"):
                state = "inchar"
                enc = None
                bbx = None
                rows = []
            elif state == "inchar":
                if line.startswith("ENCODING"):
                    enc = int(line.split()[1])
                elif line.startswith("BBX"):
                    p = line.split()
                    bbx = (int(p[1]), int(p[2]), int(p[3]), int(p[4]))  # w h xoff yoff
                elif line == "BITMAP":
                    state = "bitmap"
                elif line.startswith("ENDCHAR"):
                    state = None
            elif state == "bitmap":
                if line.startswith("ENDCHAR"):
                    state = None
                    if enc in wanted and enc not in glyphs:
                        glyphs[enc] = normalize(bbx, rows)
                else:
                    rows.append(int(line.strip(), 16))
    return glyphs


def normalize(bbx, rows):
    """BBX 字形 -> 12x12 cell (bit15=最左像素 的 16bit 行 x12)"""
    w, h, xoff, yoff = bbx
    cell = [0] * CELL
    nbytes = (w + 7) // 8
    top = ASCENT - (yoff + h)          # cell 中首行
    for r in range(h):
        cy = top + r
        if not (0 <= cy < CELL):
            continue
        v = rows[r] if r < len(rows) else 0
        bits = nbytes * 8
        out = 0
        for i in range(w):
            cx = xoff + i
            if 0 <= cx < CELL and (v >> (bits - 1 - i)) & 1:
                out |= 1 << (15 - cx)  # 左对齐: 像素 x -> bit(15-x)
        cell[cy] = out
    return cell


def collect_chars(path):
    """textscn.tsv zh 列 -> 首现顺序的唯一汉字 codepoint 列表"""
    chars = []
    seen = set()
    with path.open(encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 9:
                continue
            zh = re.sub(r"\{[0-9A-Fa-f]{2}\}", "", parts[8])
            for ch in zh:
                if "\u4e00" <= ch <= "\u9fff":
                    cp = ord(ch)
                    if cp not in seen:
                        seen.add(cp)
                        chars.append(cp)
    return chars


def emit_banks(glyphs, chars):
    files = []
    for bi, start in enumerate(range(0, len(chars), PER_BANK)):
        bank_no = FIRST_BANK + bi
        part = chars[start:start + PER_BANK]
        p = ROOT / "gfx" / ("zh_glyphs_bank%02X.asm" % bank_no)
        with p.open("w", encoding="ascii") as f:
            f.write("; bank 0x%02X - Chinese glyph bitmaps (1bpp 12x12, 24B/glyph)\n" % bank_no)
            f.write("; generated by tools/bdf2asm.py - do not edit by hand\n")
            if bi == 0:
                f.write("\nZhGlyphCount:\tequ\t%d\n" % len(chars))
            f.write("\nZhGlyphs%02X:\n" % bank_no)
            for gi, cp in enumerate(part):
                bm = glyphs[cp]
                f.write("\t; glyph %d: U+%04X\n" % (start + gi, cp))
                for ri in range(0, 12, 4):
                    bs = []
                    for r in range(ri, ri + 4):
                        bs.append("0x%02x,0x%02x" % (bm[r] >> 8, bm[r] & 0xFF))
                    f.write("\tDEFB\t" + ",".join(bs) + "\n")
            f.write("\n\t; pad to 8KB\n\tDS\t0x2000 - ($ & 0x1FFF), 0xFF\n")
        files.append(p)
    return files


def self_test(glyphs, chars):
    """ascii art 抽查"""
    samples = [c for c in (0x4E00, 0x4F4D, 0x7684, 0x4F51) if c in glyphs]
    for cp in samples[:2] + chars[:2]:
        bm = glyphs[cp]
        print("U+%04X (index %d):" % (cp, chars.index(cp)))
        for v in bm:
            print("  " + "".join("#" if (v >> (15 - i)) & 1 else "." for i in range(12)))


def main():
    chars = collect_chars(TSV)
    print("unique hanzi in textscn.tsv: %d" % len(chars))
    glyphs = parse_bdf(BDF, set(chars))
    missing = [c for c in chars if c not in glyphs]
    if missing:
        print("!! BDF 缺字:", " ".join("U+%04X" % c for c in missing))
        sys.exit(1)
    if "--test" in sys.argv:
        self_test(glyphs, chars)
        return
    files = emit_banks(glyphs, chars)
    # 未用到的 bank 保持 0xFF 骨架不变
    used = FIRST_BANK + len(files)
    print("glyph data: %d glyphs, %d bytes -> %s" %
          (len(chars), len(chars) * GLYPH_BYTES,
           ", ".join("bank 0x%02X" % (FIRST_BANK + i) for i in range(len(files)))))
    with IDX_OUT.open("w", encoding="utf-8") as f:
        f.write("# index\tcodepoint\tchar\n")
        for i, cp in enumerate(chars):
            f.write("%d\tU+%04X\t%s\n" % (i, cp, chr(cp)))
    print("index table: %s" % IDX_OUT)


if __name__ == "__main__":
    main()
