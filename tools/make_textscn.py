def main():
    src = ROOT / "texts.tsv"
    dst = ROOT / "textscn.tsv"
    rows = []
    with src.open(encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            # id kind bank addr seg x y text unk raw note
            rid, kind, bank, addr, seg, x, y, text = parts[:8]
            zh = ZH.get(rid, "")
            rows.append((rid, kind, bank, addr, seg, x, y, text, zh))

    with dst.open("w", encoding="utf-8") as f:
        f.write("# Ganbare Goemon 中文文本 (机翻初稿 2025-10-19, 人工校正于本文件迭代)\n")
        f.write("# 列: id\tkind\tbank\taddr\tseg\tx\ty\ttext(jp)\tzh\n")
        f.write("# zh 为空 = 原样保留 (图形块 {XX}/空白/密码乱码假名行)\n")
        f.write("# 已确认图形码: {67}=？ {69}=© {78}=F {66}=装饰块 {64}=。\n")
        for r in rows:
            f.write("\t".join(r) + "\n")

    # ---- 用字统计 ----
    from collections import Counter
    han = Counter()
    for r in rows:
        for ch in r[8]:
            if "\u4e00" <= ch <= "\u9fff":
                han[ch] += 1
    print(f"textscn.tsv: {len(rows)} 段")
    print(f"唯一汉字数: {len(han)}  (阈值: 方案A≤50 / 报警>600)")
    print("高频前 30:", " ".join("%s×%d" % (c, n) for c, n in han.most_common(30)))


if __name__ == "__main__":
    main()
